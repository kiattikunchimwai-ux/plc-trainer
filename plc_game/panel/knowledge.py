def sheet(kind: str) -> Know | None:
    return KNOW.get(kind)


def _val(info: KindInfo, f, props: dict | None):
    v = (props or {}).get(f.prop, info.default_of(f))
    if f.type == "choice":
        return dict(f.choices).get(str(v), v)
    if f.type == "num":
        if f.special and float(v or 0) <= f.lo:
            return f.special
        return f"{float(v):.{f.dec}f}{f.unit}"
    return v


def sheet_html(kind: str, props: dict | None = None, heading: int = 2) -> str:
    """ใบความรู้ 1 อุปกรณ์เป็น HTML (ใช้ได้ทั้งใน QTextBrowser และพิมพ์ PDF)."""
    info = CATALOG[kind]
    k = KNOW.get(kind)
    e = html.escape
    cat = dict(CATEGORIES).get(info.category, info.category)
    label = (props or {}).get("label")
    out = [f"<h{heading}>{e(info.name)}" + (f" — {e(str(label))}" if label else "") + f"</h{heading}>",
           tr("<p style='color:#888'>หมวด: {0}</p>", e(cat)), f"<p>{e(info.desc)}</p>"]
    if k:
        out += [tr("<h{0}>หลักการทำงาน</h{1}><p>{2}</p>", heading + 1, heading + 1, e(k.work)),
                tr("<h{0}>การต่อสายกับ PLC</h{1}><p>{2}</p>", heading + 1, heading + 1, e(k.wiring)),
                tr("<h{0}>ข้อควรระวัง / แนวคิดเขียนโปรแกรม</h{1}><p>{2}</p>", heading + 1, heading + 1, e(k.tips))]
    slots = info.slots()
    if slots:
        rows = "".join(
            f"<tr><td>{e(s.label)}</td><td>{e(DIR_TH.get(s.io, s.io))}</td>"
            f"<td>{e('/'.join(s.prefixes))}</td><td>{e(str((props or {}).get(s.prop, info.defaults.get(s.prop, ''))))}"
            f"{tr(' (เว้นได้)') if s.optional else ''}</td></tr>" for s in slots)
        out.append(tr("<h{0}>สัญญาณ I/O</h{1}><table border='1' cellpadding='4' cellspacing='0'><tr><th>หน้าที่</th><th>ทิศทาง</th><th>ชนิด address</th><th>ค่า</th></tr>", heading + 1, heading + 1) + rows + "</table>")
    specs = [f for f in info.specs if f.group == "spec"]
    if specs:
        rows = "".join(f"<tr><td>{e(f.label)}</td><td>{e(str(_val(info, f, props)))}</td>"
                       f"<td>{e(f.help).replace(chr(10), '<br>')}</td></tr>" for f in specs)
        out.append(tr("<h{0}>สเปก (ดาต้าชีท)</h{1}><table border='1' cellpadding='4' cellspacing='0'><tr><th>รายการ</th><th>ค่า</th><th>คำอธิบาย</th></tr>", heading + 1, heading + 1) + rows + "</table>")
    return "\n".join(out)


def handbook_html(kinds: list[str] | None = None, title: str = "") -> str:
    """ใบความรู้หลายอุปกรณ์รวมเล่ม (ค่าเริ่มต้น = ทุกชนิด ตามหมวด) — ขึ้นหน้าใหม่ทุกอุปกรณ์เมื่อพิมพ์."""
    title = title or tr("ใบความรู้อุปกรณ์ PLC Trainer")
    if kinds is None:
        order = [c for c, _ in CATEGORIES]
        kinds = sorted((k for k in CATALOG if k not in ANNOTATION),
                       key=lambda k: (order.index(CATALOG[k].category), list(CATALOG).index(k)))
    parts = [f"<div style='page-break-after:always'>{sheet_html(k)}</div>" for k in kinds]
    toc = "".join(f"<li>{html.escape(CATALOG[k].name)}</li>" for k in kinds)
    return (f"<html><head><meta charset='utf-8'><title>{html.escape(title)}</title></head><body>"
            f"<h1>{html.escape(title)}</h1><ol>{toc}</ol><div style='page-break-after:always'></div>"
            + "".join(parts) + "</body></html>")
